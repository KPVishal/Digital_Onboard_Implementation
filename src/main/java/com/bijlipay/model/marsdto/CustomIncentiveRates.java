package com.bijlipay.model.marsdto;

public class CustomIncentiveRates {
    private String add;
    private String maxValue;
    private String mechantFixed;
    private String merchantPercent;
    private String minValue;
    private String sharingFixed;
    private String sharingPercent;

    public String getAdd() {
        return add;
    }

    public void setAdd(String add) {
        this.add = add;
    }

    public String getMaxValue() {
        return maxValue;
    }

    public void setMaxValue(String maxValue) {
        this.maxValue = maxValue;
    }

    public String getMechantFixed() {
        return mechantFixed;
    }

    public void setMechantFixed(String mechantFixed) {
        this.mechantFixed = mechantFixed;
    }

    public String getMerchantPercent() {
        return merchantPercent;
    }

    public void setMerchantPercent(String merchantPercent) {
        this.merchantPercent = merchantPercent;
    }

    public String getMinValue() {
        return minValue;
    }

    public void setMinValue(String minValue) {
        this.minValue = minValue;
    }

    public String getSharingFixed() {
        return sharingFixed;
    }

    public void setSharingFixed(String sharingFixed) {
        this.sharingFixed = sharingFixed;
    }

    public String getSharingPercent() {
        return sharingPercent;
    }

    public void setSharingPercent(String sharingPercent) {
        this.sharingPercent = sharingPercent;
    }
}