package com.bijlipay.model.marsdto;

public class PartnerInformation {
    private String address;
    private String cityRefCode;
    private String cityRefLabel;
    private String contactEmail;
    private String contactMobile;
    private String dob;
    private String name;
    private String pan;
    private String pin;
    private String stateRefCode;
    private String stateRefLabel;

    public String getDob() {
        return dob;
    }

    public void setDob(String dob) {
        this.dob = dob;
    }

    public String getAddress() {
        return address;
    }

    public void setAddress(String address) {
        this.address = address;
    }

    public String getCityRefCode() {
        return cityRefCode;
    }

    public void setCityRefCode(String cityRefCode) {
        this.cityRefCode = cityRefCode;
    }

    public String getCityRefLabel() {
        return cityRefLabel;
    }

    public void setCityRefLabel(String cityRefLabel) {
        this.cityRefLabel = cityRefLabel;
    }

    public String getContactEmail() {
        return contactEmail;
    }

    public void setContactEmail(String contactEmail) {
        this.contactEmail = contactEmail;
    }

    public String getContactMobile() {
        return contactMobile;
    }

    public void setContactMobile(String contactMobile) {
        this.contactMobile = contactMobile;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getPan() {
        return pan;
    }

    public void setPan(String pan) {
        this.pan = pan;
    }

    public String getPin() {
        return pin;
    }

    public void setPin(String pin) {
        this.pin = pin;
    }

    public String getStateRefCode() {
        return stateRefCode;
    }

    public void setStateRefCode(String stateRefCode) {
        this.stateRefCode = stateRefCode;
    }

    public String getStateRefLabel() {
        return stateRefLabel;
    }

    public void setStateRefLabel(String stateRefLabel) {
        this.stateRefLabel = stateRefLabel;
    }
}
